func drawCollectionSummary(
	pdf *gofpdf.Fpdf,
	summary dto.CollectionReportSummary,
) {

	pdf.SetFont(
		"Arial",
		"B",
		10,
	)

	pdf.CellFormat(
		0,
		7,
		"COLLECTION SUMMARY",
		"",
		1,
		"L",
		false,
		0,
		"",
	)

	pdf.Ln(3)

	// Landscape A4:
	// 297mm width
	// 10mm margins
	// 277mm usable width

	cardWidth := 64.0
	cardHeight := 22.0
	gap := 6.0

	startX := 10.0
	startY := pdf.GetY()

	cards := []struct {
		title string
		value string
	}{
		{
			title: "Transactions",
			value: fmt.Sprintf(
				"%d",
				summary.TotalTransactions,
			),
		},
		{
			title: "Principal",
			value: formatPHP(
				summary.TotalPrincipal,
			),
		},
		{
			title: "Interest",
			value: formatPHP(
				summary.TotalInterest,
			),
		},
		{
			title: "Total Collection",
			value: formatPHP(
				summary.TotalCollection,
			),
		},
	}

	for i, card := range cards {

		x := startX +
			float64(i)*
				(cardWidth+gap)

		// Card border
		pdf.Rect(
			x,
			startY,
			cardWidth,
			cardHeight,
			"D",
		)

		// Title
		pdf.SetXY(
			x,
			startY+3,
		)

		pdf.SetFont(
			"Arial",
			"",
			8,
		)

		pdf.CellFormat(
			cardWidth,
			5,
			card.title,
			"",
			0,
			"C",
			false,
			0,
			"",
		)

		// Value
		pdf.SetXY(
			x,
			startY+10,
		)

		pdf.SetFont(
			"Arial",
			"B",
			11,
		)

		pdf.CellFormat(
			cardWidth,
			7,
			card.value,
			"",
			0,
			"C",
			false,
			0,
			"",
		)
	}

	pdf.SetY(
		startY + cardHeight + 6,
	)
}

func drawCollectionTable(
	pdf *gofpdf.Fpdf,
	rows []dto.CollectionReportRow,
) {

	pdf.SetFont(
		"Arial",
		"B",
		10,
	)

	pdf.CellFormat(
		0,
		7,
		"COLLECTION DETAILS",
		"",
		1,
		"L",
		false,
		0,
		"",
	)

	pdf.Ln(2)

	headers := []string{
		"Date",
		"Reference",
		"PN Number",
		"Client",
		"Principal",
		"Interest",
		"Amount Paid",
		"Channel",
	}

	widths := []float64{
		22,
		30,
		30,
		55,
		30,
		30,
		32,
		28,
	}

	// Total = 257mm
	// Landscape A4 usable width = 277mm

	drawHeader := func() {

		pdf.SetFont(
			"Arial",
			"B",
			7,
		)

		for i, header := range headers {

			pdf.CellFormat(
				widths[i],
				8,
				header,
				"1",
				0,
				"C",
				false,
				0,
				"",
			)
		}

		pdf.Ln(-1)
	}

	drawHeader()

	pdf.SetFont(
		"Arial",
		"",
		7,
	)

	for _, row := range rows {

		values := []string{
			row.PaymentDate,
			row.ReferenceNumber,
			row.PNNumber,
			row.ClientName,
			formatPHP(
				row.PrincipalApplied,
			),
			formatPHP(
				row.InterestApplied,
			),
			formatPHP(
				row.AmountPaid,
			),
			row.PaymentChannel,
		}

		for i, value := range values {

			align := "L"

			if i >= 4 && i <= 6 {
				align = "R"
			}

			pdf.CellFormat(
				widths[i],
				7,
				value,
				"1",
				0,
				align,
				false,
				0,
				"",
			)
		}

		pdf.Ln(-1)
	}

	// ========================================
	// TOTAL
	// ========================================

	var principal float64
	var interest float64
	var collection float64

	for _, row := range rows {

		principal +=
			row.PrincipalApplied

		interest +=
			row.InterestApplied

		collection +=
			row.AmountPaid
	}

	pdf.SetFont(
		"Arial",
		"B",
		7,
	)

	labelWidth :=
		widths[0] +
			widths[1] +
			widths[2] +
			widths[3]

	pdf.CellFormat(
		labelWidth,
		8,
		"TOTAL",
		"1",
		0,
		"R",
		false,
		0,
		"",
	)

	pdf.CellFormat(
		widths[4],
		8,
		formatPHP(principal),
		"1",
		0,
		"R",
		false,
		0,
		"",
	)

	pdf.CellFormat(
		widths[5],
		8,
		formatPHP(interest),
		"1",
		0,
		"R",
		false,
		0,
		"",
	)

	pdf.CellFormat(
		widths[6],
		8,
		formatPHP(collection),
		"1",
		0,
		"R",
		false,
		0,
		"",
	)

	pdf.CellFormat(
		widths[7],
		8,
		"",
		"1",
		0,
		"L",
		false,
		0,
		"",
	)

	pdf.Ln(-1)

}

