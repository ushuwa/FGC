type ReportPDFService struct {
	outputDirectory string
}

func NewReportPDFService(
	outputDirectory string,
) *ReportPDFService {
	return &ReportPDFService{
		outputDirectory: outputDirectory,
	}
}

func (s *ReportPDFService) GenerateCollectionReport(
	data *dto.CollectionReportData,
	dateFrom string,
	dateTo string,
) (string, error) {

	if err := os.MkdirAll(
		s.outputDirectory,
		0755,
	); err != nil {
		return "", err
	}

	pdf := gofpdf.New(
		"L",
		"mm",
		"A4",
		"",
	)

	pdf.SetTitle(
		"Summary of Collection",
		true,
	)

	pdf.SetAuthor(
		"FGC",
		true,
	)

	pdf.SetMargins(
		10,
		10,
		10,
	)

	pdf.SetAutoPageBreak(
		true,
		15,
	)

	pdf.SetFooterFunc(
		func() {

			pdf.SetY(-12)

			pdf.SetFont(
				"Arial",
				"",
				7,
			)

			pdf.CellFormat(
				0,
				5,
				"Generated by FGC",
				"",
				0,
				"L",
				false,
				0,
				"",
			)

			pdf.CellFormat(
				0,
				5,
				fmt.Sprintf(
					"Page %d",
					pdf.PageNo(),
				),
				"",
				0,
				"R",
				false,
				0,
				"",
			)
		},
	)

	pdf.AddPage()

	drawCollectionHeader(
		pdf,
		dateFrom,
		dateTo,
	)

	drawCollectionSummary(
		pdf,
		data.Summary,
	)

	pdf.Ln(5)

	drawCollectionTable(
		pdf,
		data.Rows,
	)

	// drawCollectionFooter(
	// 	pdf,
	// )

	filename := fmt.Sprintf(
		"summary_collection_%s.pdf",
		time.Now().Format(
			"20060102_150405",
		),
	)

	path := filepath.Join(
		s.outputDirectory,
		filename,
	)

	if err := pdf.OutputFileAndClose(
		path,
	); err != nil {
		return "", err
	}

	return path, nil
}

