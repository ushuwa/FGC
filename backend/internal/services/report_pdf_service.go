func formatPHP(
	value float64,
) string {

	return fmt.Sprintf(
		"PHP %.2f",
		value,
	)
}

func (s *ReportPDFService) GenerateAmortizationReport(
	data *dto.AmortizationReportData,
) (string, error) {

	if data == nil || len(data.Rows) == 0 {
		return "", fmt.Errorf(
			"no amortization data available",
		)
	}

	if err := os.MkdirAll(
		s.outputDirectory,
		0755,
	); err != nil {
		return "", err
	}

	pdf := gofpdf.New(
		"L",
		"mm",
		"A4",
		"",
	)

	pdf.SetTitle(
		"Loan Account Amortization",
		true,
	)

	pdf.SetAuthor(
		"FGC",
		true,
	)

	pdf.SetMargins(
		10,
		10,
		10,
	)

	pdf.SetAutoPageBreak(
		true,
		15,
	)

	pdf.SetFooterFunc(
		func() {

			pdf.SetY(-12)

			pdf.SetFont(
				"Arial",
				"",
				7,
			)

			pdf.CellFormat(
				0,
				5,
				"Generated by FGC",
				"",
				0,
				"L",
				false,
				0,
				"",
			)

			pdf.CellFormat(
				0,
				5,
				fmt.Sprintf(
					"Page %d",
					pdf.PageNo(),
				),
				"",
				0,
				"R",
				false,
				0,
				"",
			)
		},
	)

	pdf.AddPage()

	drawAmortizationHeader(
		pdf,
		data.Loan,
	)

	drawLoanInformation(
		pdf,
		data.Loan,
	)

	drawAmortizationSummary(
		pdf,
		data.Summary,
	)

	pdf.AddPage()

	drawAmortizationTable(
		pdf,
		data.Rows,
		data.Summary,
	)

	filename := fmt.Sprintf(
		"loan_amortization_%s_%s.pdf",
		data.Loan.PNNumber,
		time.Now().Format(
			"20060102_150405",
		),
	)

	path := filepath.Join(
		s.outputDirectory,
		filename,
	)

	if err := pdf.OutputFileAndClose(
		path,
	); err != nil {
		return "", err
	}

	return path, nil
}

