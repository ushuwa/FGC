func (s *ReportPDFService) GenerateLoanMaturityReport(
	data *dto.LoanMaturityReportData,
) (string, error) {

	if data == nil {
		return "", fmt.Errorf(
			"loan maturity report data is nil",
		)
	}

	if err := os.MkdirAll(
		s.outputDirectory,
		0755,
	); err != nil {
		return "", err
	}

	pdf := gofpdf.New(
		"L",
		"mm",
		"A4",
		"",
	)

	pdf.SetTitle(
		"Loan Maturity and Due Report",
		true,
	)

	pdf.SetAuthor(
		"FGC",
		true,
	)

	pdf.SetMargins(
		10,
		10,
		10,
	)

	pdf.SetAutoPageBreak(
		true,
		15,
	)

	pdf.SetFooterFunc(
		func() {

			pdf.SetY(-12)

			pdf.SetFont(
				"Arial",
				"",
				7,
			)

			pdf.CellFormat(
				0,
				5,
				"Generated by FGC",
				"",
				0,
				"L",
				false,
				0,
				"",
			)

			pdf.CellFormat(
				0,
				5,
				fmt.Sprintf(
					"Page %d",
					pdf.PageNo(),
				),
				"",
				0,
				"R",
				false,
				0,
				"",
			)
		},
	)

	// ========================================
	// PAGE 1
	// ========================================

	pdf.AddPage()

	drawLoanMaturityHeader(pdf)

	drawLoanMaturitySummary(
		pdf,
		data.Summary,
	)

	drawLoanMaturityBuckets(
		pdf,
		data.Summary,
	)

	// ========================================
	// PAGE 2+
	// ========================================

	pdf.AddPage()

	drawLoanMaturityTable(
		pdf,
		data.Rows,
	)

	filename := fmt.Sprintf(
		"loan_maturity_due_%s.pdf",
		time.Now().Format(
			"20060102_150405",
		),
	)

	path := filepath.Join(
		s.outputDirectory,
		filename,
	)

	if err := pdf.OutputFileAndClose(
		path,
	); err != nil {
		return "", err
	}

	return path, nil
}

